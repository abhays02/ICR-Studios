  await page.getByRole('button',{name:'Fit',exact:true}).click()
  await page.getByRole('button',{name:'Undo',exact:true}).click()
  await page.getByRole('button',{name:'Redo',exact:true}).click()
  await page.getByRole('button',{name:'Create ROI'}).click()
  await page.getByLabel('Label',{exact:true}).fill('Smoke numeric boxes')
  await page.getByLabel('Type',{exact:true}).selectOption('comb')
