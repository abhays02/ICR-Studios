  assert.match(jobText,/9 \/ 9 fields processed/)
  assert.match(jobText,/[1-9]\d* actual SSE events received/)
  assert.equal(await page.getByLabel('Immutable model raw text',{exact:true}).inputValue(),'')
  checks.push('real queued local OCR, authenticated streaming SSE, honest missing-model failure and no invented raw text')
  await page.getByLabel('Human-reviewed value',{exact:true}).fill('SMOKE REVIEWED')
  await page.getByRole('button',{name:'Save human correction',exact:true}).click()
  await page.getByText(/Reviewed by operator/).waitFor()
  assert.equal(await page.getByLabel('Immutable model raw text',{exact:true}).inputValue(),'')
  await page.getByRole('button',{name:'Compare raw / reviewed / provenance'}).click()
  await page.getByRole('dialog',{name:'Evidence comparison'}).waitFor()
  assert.match(await page.getByRole('dialog').textContent(),/SMOKE REVIEWED/)
  assert.match(await page.getByRole('dialog').textContent(),/raw_text/)
  await page.getByRole('button',{name:'Close comparison'}).click()
  checks.push('revision-checked manual correction preserves raw null; actual provenance drawer')
  await page.getByRole('button',{name:'Finalize human review',exact:true}).click()
