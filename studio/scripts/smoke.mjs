  await page.getByLabel('Selected field',{exact:true}).selectOption('full_name')
  checks.push('create/delete ROI, editable label/type/numeric flag, ordered comb cells, keyboard undo/redo')
  await page.getByLabel('New immutable version',{exact:true}).fill('smoke_'+Date.now())
  await page.getByRole('button',{name:'Save new template version',exact:true}).click()
  await page.getByText(/Immutable template saved/).waitFor()
  checks.push('undo/redo and immutable new template version saved to backend')
  const upload=page.getByLabel('Upload scans',{exact:true})
