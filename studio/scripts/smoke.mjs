  checks.push('six actual gallery images; only first five importable; synthetic labels and alignment block')
  await page.getByRole('button',{name:'Import fixture'}).first().click()
  await page.getByRole('heading',{name:'CAR document',exact:true}).waitFor()
  await page.locator('svg image').waitFor()
  assert.equal(await page.locator('svg .roi:not(.subroi)').count(),9)
  checks.push('real gallery import; canonical full resolution image; nine template overlays')
  await page.getByText('Edit ROI & recognition type',{exact:true}).click()
  const left=page.getByLabel('Left x',{exact:true})
  const oldLeft=Number(await left.inputValue())
  const box=await page.locator('svg').evaluate(svg=>{
    const rect=svg.querySelector('[aria-label="Full name roi 1"]')
    const p=new DOMPoint(Number(rect.getAttribute('x'))+100,Number(rect.getAttribute('y'))+30).matrixTransform(svg.getScreenCTM())
    return {x:p.x,y:p.y}
  })
  await page.mouse.move(box.x,box.y)
  await page.mouse.down()
